"""IDs autoincrementais em users, reviews e comments

Converte as PKs para GENERATED BY DEFAULT AS IDENTITY (se ainda não forem)
e ajusta a sequence para continuar depois do maior id existente.

Revision ID: 0002
Revises: 0001
Create Date: 2026-11-06
"""
from typing import Sequence, Union

from alembic import op

revision: str = "0002"
down_revision: Union[str, Sequence[str], None] = "0001"
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None

TABELAS = ("users", "reviews", "comments")


def upgrade() -> None:
    for tabela in TABELAS:
        op.execute(f"""
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_attribute
                    WHERE attrelid = '{tabela}'::regclass
                      AND attname = 'id'
                      AND attidentity <> ''
                ) THEN
                    ALTER TABLE {tabela}
                        ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
                END IF;
            END $$;
        """)
        # Tabela vazia: próximo id = 1. Com dados: próximo id = MAX(id) + 1.
        op.execute(f"""
            SELECT setval(
                pg_get_serial_sequence('{tabela}', 'id'),
                COALESCE(MAX(id), 1),
                MAX(id) IS NOT NULL
            )
            FROM {tabela};
        """)


def downgrade() -> None:
    for tabela in reversed(TABELAS):
        op.execute(f"ALTER TABLE {tabela} ALTER COLUMN id DROP IDENTITY IF EXISTS;")
